export const SHARED_DEPARTMENTS = ['Claude Build Studio', 'Codex Review & Balance', 'Grok Dispatch', 'Gemini Research', 'Qwen Local Assistance'];

// Routing and seat allocation continue to use the original role keys. Only
// display labels change, so saved tasks and live actor metadata remain valid.
export function officeRoleLabel(role, provider = '', worker = {}) {
  if (provider === 'Local Qwen' || provider === 'local-qwen') return 'Local Assistant';
  if (role === 'Manager' && /^(Grok|grok)$/.test(provider)) return 'Dispatch Lead';
  if (role === 'Researcher') return 'Research Analyst';
  if (role === 'Admin') return 'Coordinator';
  if (role === 'Worker' && /^(Claude Code|claude|Codex|codex)$/.test(provider)) return 'Builder';
  if (role === 'Worker') return 'Agent';
  if (role === 'Helper') {
    const metadata = [worker.agentRole, worker.role, worker.agentType, worker.category].filter(Boolean).join(' ');
    const noncoding = /\b(design|content|research|planning|analysis|artist|writer|facilitat|coordinat)/i.test(metadata);
    return /^(Claude Code|claude|Codex|codex)$/.test(provider) && !noncoding ? 'Builder' : 'Helper';
  }
  return role || 'Agent';
}

export function officeRoleDescription(agent = {}) {
  if (agent.provider === 'Local Qwen') return 'Preliminary text assistance only; human verification required. No code, review or final deliverables.';
  if (agent.provider === 'Codex') return 'Reviews implementation, balances game systems and gives release sign-off.';
  if (agent.provider === 'Gemini') return 'Researches with read-only access; never reviews.';
  if (agent.provider === 'Grok') return 'Coordinates requests and dispatches work to the team.';
  return 'Builds and implements the team’s projects.';
}

// Normalize only names generated by the local runner; preserve custom identities.
export function officeAgentLabel(value) {
  return typeof value === 'string' ? value.replace(/^(Claude Code|Codex|Gemini|Grok|Local Qwen) task worker$/, '$1 task agent') : value;
}

const PROVIDERS = [
  { key: 'claude', name: 'Claude Code', department: SHARED_DEPARTMENTS[0] },
  { key: 'codex', name: 'Codex', department: SHARED_DEPARTMENTS[1] },
  { key: 'grok', name: 'Grok', department: SHARED_DEPARTMENTS[2] },
  { key: 'gemini', name: 'Gemini', department: SHARED_DEPARTMENTS[3] },
  { key: 'local-qwen', name: 'Local Qwen', department: SHARED_DEPARTMENTS[4] },
];
// Preserve the original four providers' reservations when Qwen joins.
const LEGACY_SEAT_STRIDE = 4, LOCAL_SEAT_START = 1000000;
const LIVE_STATUSES = new Set(['working', 'idle', 'waiting']);
const clean = (value, max = 400) => typeof value === 'string' && !/[\x00-\x1f\x7f]/.test(value) ? value.trim().slice(0, max) : '';
const nativeId = value => typeof value === 'string' && value.length <= 512 && /^[a-zA-Z0-9][a-zA-Z0-9_.:@/-]*$/.test(value) ? value : '';
const words = value => clean(value).replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase().replace(/[_:/.-]+/g, ' ').replace(/\s+/g, ' ').trim();
const time = value => { const parsed = typeof value === 'number' ? value : Date.parse(value); return Number.isFinite(parsed) ? parsed : 0; };

function roleFor(value) {
  const text = words(value);
  if (/\b(test(?:er|ing|s)?|review(?:er|ing)?|quality|qa|audit(?:or|ing)?|security|validation|verification|bugbot)\b/.test(text)) return 'Tester';
  if (/\b(admin(?:istrator|istration)?|operations?|operator|orchestrat(?:or|ion|e|ing)|infrastructure|infra|runtime|hooks?|automation|scheduler|environment|deployment|release)\b/.test(text)) return 'Admin';
  if (/\b(facilitat(?:or|ion)|coordinator|coordination|planning|planner|plan|research(?:er|ing)?|analysis|analyst|architecture|architect)\b/.test(text)) return 'Facilitator';
  if (/\b(helper|implement(?:er|ation)?|developer|engineering|engineer|coder|coding|backend|frontend|builder)\b/.test(text)) return 'Helper';
  return null;
}

// Roles use only public actor/role/tool metadata. A root coordinator remains a
// Facilitator even when it temporarily runs a test, edits a file, or browses.
export function codexOfficeRole(worker = {}) {
  const type = words(worker.agentType);
  if (type === 'office task runner' && ['Facilitator','Admin','Helper','Tester'].includes(worker.agentRole)) return worker.agentRole;
  if (worker.isSubagent === false || ['main', 'root', 'coordinator', 'codex coordinator'].includes(type) || clean(worker.agentPath) === '/root') return 'Facilitator';
  for (const value of [worker.agentRole, worker.role, worker.agentType, worker.agentPath, worker.name, worker.tool, worker.lastTool]) {
    const found = roleFor(value);
    if (found) return found;
  }
  return 'Helper';
}

function sanitizedWorker(original, provider, available) {
  const id = nativeId(original?.id);
  if (!id) return null;
  const status = available ? (LIVE_STATUSES.has(original.status) ? original.status : 'idle') : 'offline';
  const worker = { id, provider: provider.name, status, isSubagent: typeof original.isSubagent === 'boolean' ? original.isSubagent : null, observed: original.observed !== false };
  for (const field of ['sessionId', 'agentType', 'name', 'tool', 'lastTool', 'lastToolOutcome', 'updatedAt', 'lastToolAt', 'skillId', 'agentRole', 'agentPath', 'parentSessionId', 'lastEvent', 'category']) {
    const value = clean(original[field], field === 'sessionId' || field === 'parentSessionId' ? 512 : 400);
    worker[field] = value || null;
  }
  worker.cwd = clean(original.cwd, 2048);
  if (!available) worker.tool = null;
  // A detected session without an observed lifecycle event does not establish
  // that it is working, even if an inconsistent source reports that status.
  if (worker.observed === false && worker.status === 'working') { worker.status = 'idle'; worker.tool = null; }
  return worker;
}

export function officeBridgeAvailable(state = {}) {
  return !state.error && state.connected !== false && state.metadataAvailable !== false;
}

function skillMetadata(skill) {
  if (!skill || !nativeId(skill.id)) return null;
  return { id: skill.id, name: clean(skill.name), description: clean(skill.description, 1800), category: clean(skill.category), source: clean(skill.source) };
}

function latestWorkers(agents) {
  const byId = new Map();
  for (const worker of Array.isArray(agents) ? agents : []) {
    if (!nativeId(worker?.id)) continue;
    const previous = byId.get(worker.id);
    if (!previous || time(worker.updatedAt) >= time(previous.updatedAt)) byId.set(worker.id, worker);
  }
  return [...byId.values()].sort((a, b) => a.id.localeCompare(b.id));
}

// Only observed runtime identities become people. Installed skill catalogs may
// enrich a worker profile, but never create idle or active figures themselves.
export function buildSharedRoster(states = {}, seats = new Map()) {
  const records = [];
  for (const [zoneIndex, provider] of PROVIDERS.entries()) {
    const state = states[provider.key] || {};
    const available = officeBridgeAvailable(state);
    const skills = (Array.isArray(state.skills) ? state.skills : []).map(skillMetadata).filter(Boolean);
    for (const original of latestWorkers(state.agents)) {
      if (original.status === 'offline') continue;
      const worker = sanitizedWorker(original, provider, available);
      if (!worker) continue;
      const skill = skills.find(item => item.id === worker.skillId) || null;
      const role = provider.key === 'codex' ? codexOfficeRole(worker) : provider.key === 'grok' ? worker.agentRole || 'Manager' : provider.key === 'gemini' ? 'Researcher' : provider.key === 'local-qwen' ? 'Helper' : 'Worker';
      records.push({
        id: `shared:${provider.key}:${worker.id}`, provider: provider.name, officeZone: provider.key, zoneIndex,
        floor: 3, kind: 'live', name: worker.name || (provider.key === 'codex' ? `Codex ${role.toLowerCase()}` : provider.name),
        role, department: provider.department,
        description: available ? `${provider.name} ${worker.isSubagent ? 'subagent' : 'session'}${skill?.name ? ` using ${skill.name}` : ''}.` : `${provider.name} activity is unavailable.`,
        liveStatus: worker.status, runtimeAgents: [worker],
        skillId: worker.skillId, skill: skill || undefined, skills: worker.skillId ? [worker.skillId] : [],
      });
    }
  }
  // Keep reservations when a worker temporarily disappears or its bridge is
  // offline. Poll order, status changes and another provider cannot move it.
  const occupied = new Set();
  for (const [id, index] of [...seats.entries()].sort(([a], [b]) => String(a).localeCompare(String(b)))) {
    const zone = typeof id === 'string' ? PROVIDERS.findIndex(provider => id.startsWith(`shared:${provider.key}:`)) : -1;
    if (zone < 0 || !Number.isSafeInteger(index) || index < 0 || (zone === 4 ? index < LOCAL_SEAT_START : index >= LOCAL_SEAT_START || index % LEGACY_SEAT_STRIDE !== zone) || occupied.has(index)) seats.delete(id);
    else occupied.add(index);
  }
  for (const record of [...records].sort((a, b) => a.id.localeCompare(b.id))) {
    if (seats.has(record.id)) continue;
    let index = record.zoneIndex === 4 ? LOCAL_SEAT_START : record.zoneIndex;
    while (occupied.has(index)) index += LEGACY_SEAT_STRIDE;
    seats.set(record.id, index);
    occupied.add(index);
  }
  return records.map(({ zoneIndex, ...record }) => ({ ...record, index: seats.get(record.id), officeSlot: Math.floor((seats.get(record.id) - (record.provider === 'Local Qwen' ? LOCAL_SEAT_START : 0)) / LEGACY_SEAT_STRIDE) })).sort((a, b) => a.index - b.index);
}

export function workingOfficeAgents(roster = []) {
  return roster.filter(agent => agent.liveStatus === 'working' && agent.runtimeAgents?.some(worker => worker.status === 'working' && worker.observed !== false)).sort((a, b) => a.index - b.index);
}

export function resolveSharedSelection(roster = [], selected) {
  if (!selected) return null;
  const provider = selected.provider || selected.runtimeAgents?.[0]?.provider || PROVIDERS.find(item => selected.id?.startsWith(`shared:${item.key}:`))?.name;
  const direct = roster.find(agent => agent.id === selected.id && (!provider || agent.provider === provider));
  const workerId = selected.runtimeAgents?.[0]?.id;
  const found = direct || (provider && workerId ? roster.find(agent => agent.provider === provider && agent.runtimeAgents?.some(worker => worker.id === workerId)) : null);
  if (found) return found;
  return { ...selected, liveStatus: 'offline', runtimeAgents: (selected.runtimeAgents || []).map(worker => ({ ...worker, status: 'offline', tool: null })) };
}

// Preserve the original records and links verbatim. Legacy positions are
// historical context; they do not identify any worker in the shared office.
export function migrateOfficeRecords(records) {
  if (!Array.isArray(records)) return [];
  return records.map(record => {
    if (!record || typeof record !== 'object' || Array.isArray(record)) return record;
    const migrated = { ...record, floor: 3 };
    if (!Object.hasOwn(record, 'legacyFloor')) migrated.legacyFloor = record.floor;
    if (Object.hasOwn(record, 'agentIndex') && !Object.hasOwn(record, 'legacyAgentIndex')) migrated.legacyAgentIndex = record.agentIndex;
    if (Object.hasOwn(record, 'index') && !Object.hasOwn(record, 'legacyIndex')) migrated.legacyIndex = record.index;
    return migrated;
  });
}

// Runner identities originate in actual CLI session events. Match by native
// session before overlaying activity so one worker never becomes two figures.
export function withTaskWorkers(connection = {}, runtime = {}, provider) {
  const workers = (runtime.agents || []).filter(worker => worker.provider === provider);
  if (!workers.length) return connection;
  const agents = [...(connection.agents || [])];
  for (const worker of workers) {
    const index = agents.findIndex(agent => agent.id === worker.id || (worker.sessionId && agent.sessionId === worker.sessionId && agent.isSubagent !== true));
    const active = { ...worker, agentRole: worker.role === 'any' ? 'Helper' : worker.role || 'Helper' };
    if (index < 0) agents.push(active);
    else agents[index] = { ...agents[index], ...active, id: agents[index].id };
  }
  return { ...connection, agents, connected: true, metadataAvailable: true, error: null };
}
