#!/usr/bin/env node
// Installs the local Claude Code observer and skill-backed user subagents.
// Official references:
// https://code.claude.com/docs/en/hooks
// https://code.claude.com/docs/en/sub-agents#preload-skills-into-subagents
// https://code.claude.com/docs/en/skills#choose-where-skills-load
import { readFile, writeFile, mkdir, lstat, rename, unlink } from 'node:fs/promises';
import { homedir } from 'node:os';
import path from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';

export const HOOK_EVENTS = ['SessionStart', 'UserPromptSubmit', 'PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'Notification', 'Stop', 'StopFailure', 'SessionEnd', 'SubagentStart', 'SubagentStop'];
export const OWN_MARKER = 'Generated by AI Office. Managed file.';
const PLUGIN_KEY = 'gamedev@awesome-gamedev-agent-skills';
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));

const shellQuote = value => `'${String(value).replace(/'/g, `'\\''`)}'`;
const json = value => `${JSON.stringify(value, null, 2)}\n`;

async function readOptional(file) {
  try {
    const stat = await lstat(file);
    if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`Refusing to replace a non-regular file: ${file}`);
    return await readFile(file, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

function parseObject(source, file) {
  let value;
  try { value = JSON.parse(source); } catch { throw new Error(`Invalid JSON in ${file}; no files were changed.`); }
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`Expected an object in ${file}; no files were changed.`);
  return value;
}

function frontmatterValue(source, key) {
  const header = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!header) return '';
  const lines = header[1].split(/\r?\n/);
  const index = lines.findIndex(line => line.startsWith(`${key}:`));
  if (index < 0) return '';
  let value = lines[index].slice(key.length + 1).trim();
  if (/^[>|][+-]?$/.test(value)) {
    const continuation = [];
    for (const line of lines.slice(index + 1)) {
      if (line && !/^\s/.test(line)) break;
      continuation.push(line.trim());
    }
    value = continuation.join(' ');
  }
  return value.replace(/^(['"])([\s\S]*)\1$/, '$2').replace(/\s+/g, ' ').trim();
}

async function installedSkills(claudeDir, settings) {
  if (settings.enabledPlugins?.[PLUGIN_KEY] !== true) throw new Error(`Enable ${PLUGIN_KEY} in Claude Code before connecting AI Office.`);
  const registryFile = path.join(claudeDir, 'plugins', 'installed_plugins.json');
  const registry = parseObject(await readFile(registryFile, 'utf8'), registryFile);
  const versions = registry.plugins?.[PLUGIN_KEY];
  if (!Array.isArray(versions) || !versions.length) throw new Error(`${PLUGIN_KEY} is not installed in ${claudeDir}.`);
  const installations = [...versions].sort((a, b) => String(b.lastUpdated || b.installedAt || '').localeCompare(String(a.lastUpdated || a.installedAt || '')));
  const installation = installations.find(entry => entry.scope === 'user') || installations[0];
  if (!path.isAbsolute(installation.installPath || '')) throw new Error('The installed gamedev plugin has no absolute install path.');
  const root = path.resolve(installation.installPath);
  // The marketplace manifest lists the exact skill directories that the active
  // gamedev plugin exposes, including its router outside the skills directory.
  const manifestFile = path.join(root, '.claude-plugin', 'marketplace.json');
  const manifest = parseObject(await readFile(manifestFile, 'utf8'), manifestFile);
  const definition = manifest.plugins?.find(plugin => plugin.name === 'gamedev');
  if (!Array.isArray(definition?.skills)) throw new Error('The installed gamedev plugin does not declare its skill catalog.');
  const seen = new Set();
  const skills = [];
  for (const directory of definition.skills) {
    if (typeof directory !== 'string') throw new Error('Invalid gamedev skill directory.');
    const file = path.resolve(root, directory, 'SKILL.md');
    if (!file.startsWith(`${root}${path.sep}`)) throw new Error('Gamedev skill directory escapes its installed plugin.');
    const source = await readFile(file, 'utf8');
    const name = frontmatterValue(source, 'name');
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) || seen.has(name)) throw new Error(`Invalid or duplicate skill name in ${file}`);
    seen.add(name);
    skills.push({ name, description: frontmatterValue(source, 'description'), file, invocation: `gamedev:${name}` });
  }
  if (!seen.has('router') || skills.length < 2) throw new Error('The gamedev catalog must include the router and topic skills.');
  return { root, version: installation.version || '', skills };
}

function agentFile(skill, topics) {
  const router = skill.name === 'router';
  const name = router ? 'ai-office-gamedev-router' : `ai-office-${skill.name}`;
  const description = router
    ? 'Game-development coordinator. Use proactively to detect the engine and select the right gamedev specialists and skills.'
    : `Game-development specialist for ${skill.name}. ${skill.description.slice(0, 260)}`;
  const catalog = router ? `\nAvailable topic skills and their installed fallback files:\n${topics.map(topic => `- \`${topic.invocation}\` — \`${topic.file}\` (specialist: \`ai-office-${topic.name}\`).`).join('\n')}\n` : '';
  return {
    name,
    content: `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\nskills:\n  - ${JSON.stringify(skill.invocation)}\n---\n\n<!-- ${OWN_MARKER} -->\n\nYou are the AI Office ${router ? 'game-development coordinator' : `${skill.name} specialist`} on the Claude Code floor (floor 2). Work on the user's assigned task using the installed awesome-gamedev-agent-skills plugin.\n\nYour \`${skill.invocation}\` skill is preloaded through the skills frontmatter. Follow its instructions and open its supporting references only when needed. If it was not preloaded, load it with the Skill tool using \`${skill.invocation}\`. If Claude reports the skill unavailable, read the installed source at \`${skill.file}\` and resolve references relative to that file's directory.\n\n${router ? 'Detect the project engine and task, select the smallest appropriate combination of topic skills, and load those skills before acting. Every catalog skill remains available through the Skill tool, with the exact installed source files below as fallbacks. The parent session can delegate focused work to the corresponding ai-office specialist when parallel work would help.' : 'Stay focused on this specialty. For another engine, genre, discipline, or workflow, load gamedev:router and the smallest relevant additional skills rather than assuming this specialty covers everything.'}\n\nInherit the parent session's model, tools, and permission rules. Carry out the assigned work and verify the result with appropriate project checks. Report the changes, checks, and remaining blockers clearly. AI Office observes your normal Claude lifecycle; no manual status commands are needed.\n${catalog}`,
  };
}

function mergeHooks(settings, hookPath) {
  if (settings.hooks !== undefined && (!settings.hooks || typeof settings.hooks !== 'object' || Array.isArray(settings.hooks))) throw new Error('settings.hooks must be an object; no files were changed.');
  const command = `${shellQuote(process.execPath)} ${shellQuote(hookPath)} --ai-office-managed`;
  const hooks = { ...settings.hooks };
  for (const event of HOOK_EVENTS) {
    const current = hooks[event] || [];
    if (!Array.isArray(current)) throw new Error(`settings.hooks.${event} must be an array; no files were changed.`);
    const retained = current.flatMap(group => {
      if (!group || !Array.isArray(group.hooks)) return [group];
      const remaining = group.hooks.filter(hook => !(hook?.type === 'command' && typeof hook.command === 'string' && hook.command.includes(shellQuote(hookPath)) && hook.command.endsWith(' --ai-office-managed')));
      if (remaining.length === group.hooks.length) return [group];
      return remaining.length ? [{ ...group, hooks: remaining }] : [];
    });
    // Complete the tiny local write before Claude emits the next lifecycle
    // event. Background hooks could finish out of order and revive an agent
    // after Stop. The observer stays silent, fails open, and has its own 900ms
    // deadline in addition to Claude's one-second timeout.
    hooks[event] = [...retained, { hooks: [{ type: 'command', command, timeout: 1 }] }];
  }
  return { ...settings, hooks };
}

async function assertDirectory(directory) {
  try {
    const stat = await lstat(directory);
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error(`Refusing a non-directory or symlink: ${directory}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
}

async function atomicWrite(file, content) {
  await mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
  const temporary = path.join(path.dirname(file), `.${path.basename(file)}.${randomUUID()}.tmp`);
  try {
    await writeFile(temporary, content, { flag: 'wx', mode: 0o600 });
    await rename(temporary, file);
  } finally { await unlink(temporary).catch(() => {}); }
}

export async function connectClaude({ claudeDir = process.env.CLAUDE_CONFIG_DIR || path.join(homedir(), '.claude') } = {}) {
  claudeDir = path.resolve(claudeDir);
  const settingsFile = path.join(claudeDir, 'settings.json');
  const originalSettings = await readOptional(settingsFile);
  const settings = parseObject(originalSettings || '{}', settingsFile);
  const catalog = await installedSkills(claudeDir, settings);
  const officeDir = path.join(claudeDir, 'ai-office');
  const agentsDir = path.join(claudeDir, 'agents');
  const hookPath = path.join(officeDir, 'hook.mjs');
  const topics = catalog.skills.filter(skill => skill.name !== 'router');
  const agents = catalog.skills.map(skill => agentFile(skill, topics));
  for (const directory of [claudeDir, officeDir, agentsDir, path.join(officeDir, 'events'), path.join(officeDir, 'backups')]) await assertDirectory(directory);
  const planned = [
    { file: hookPath, content: await readFile(path.join(scriptDirectory, 'claude-hook.mjs'), 'utf8'), managed: true },
    ...agents.map(agent => ({ file: path.join(agentsDir, `${agent.name}.md`), content: agent.content, managed: true })),
    { file: settingsFile, content: json(mergeHooks(settings, hookPath)), managed: false },
  ];
  const changes = [];
  for (const entry of planned) {
    entry.previous = await readOptional(entry.file);
    if (entry.managed && entry.previous !== null && !entry.previous.includes(OWN_MARKER)) throw new Error(`An unrelated file already exists at ${entry.file}; no files were changed.`);
    if (entry.previous !== entry.content) changes.push(entry);
  }
  let backupDirectory = null;
  if (changes.length) {
    backupDirectory = path.join(officeDir, 'backups', `${new Date().toISOString().replace(/[:.]/g, '-')}-${randomUUID()}`);
    await mkdir(backupDirectory, { recursive: true, mode: 0o700 });
    for (const entry of changes) {
      if (entry.previous === null) continue;
      const relative = path.relative(claudeDir, entry.file);
      const backup = path.join(backupDirectory, relative);
      await mkdir(path.dirname(backup), { recursive: true, mode: 0o700 });
      await writeFile(backup, entry.previous, { flag: 'wx', mode: 0o600 });
    }
    await writeFile(path.join(backupDirectory, 'manifest.json'), json({ createdAt: new Date().toISOString(), changed: changes.map(entry => ({ path: path.relative(claudeDir, entry.file), existed: entry.previous !== null })) }), { flag: 'wx', mode: 0o600 });
    // Save all backups before changing any configuration or generated agent.
    for (const entry of changes) await atomicWrite(entry.file, entry.content);
  }
  await mkdir(path.join(officeDir, 'events'), { recursive: true, mode: 0o700 });
  return { changedFiles: changes.length, specialists: topics.length, router: 'ai-office-gamedev-router', hookPath, eventsDirectory: path.join(officeDir, 'events'), backupDirectory, pluginRoot: catalog.root, pluginVersion: catalog.version };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const arguments_ = process.argv.slice(2);
  let claudeDir;
  if (arguments_.length) {
    if (arguments_.length !== 2 || arguments_[0] !== '--claude-dir') {
      console.error('Usage: node scripts/connect-claude.mjs [--claude-dir /absolute/claude/config]');
      process.exitCode = 1;
    } else claudeDir = arguments_[1];
  }
  if (!process.exitCode) {
    connectClaude({ claudeDir }).then(result => {
      console.log(json(result).trimEnd());
      console.log('Restart existing Claude Code sessions to load the hooks and agents.');
    }).catch(error => {
      console.error(`AI Office connection failed: ${error.message}`);
      process.exitCode = 1;
    });
  }
}
