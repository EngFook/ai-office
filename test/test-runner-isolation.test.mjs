import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const run = promisify(execFile);
test('npm test child ignores every caller office selector including custom config and future overrides', async t => {
  const root = await mkdtemp(path.join(tmpdir(), 'office-runner-env-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const config = path.join(root, 'real-office.json'), check = path.join(root, 'isolated.test.mjs'), marker = path.join(root, 'result.txt');
  await writeFile(config, JSON.stringify({ mode: 'enabled', title: 'Wrong real office' }));
  await writeFile(check, `import {writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {loadOfficeConfig} from ${JSON.stringify(new URL('../server/office-config.mjs', import.meta.url).href)};
assert.equal(process.env.AI_OFFICE_CONFIG, undefined);
assert.equal(process.env.AI_OFFICE_URL, undefined);
assert.equal(process.env.AI_OFFICE_MODE, undefined);
assert.equal(process.env.AI_OFFICE_WORKSPACE, undefined);
assert.equal(process.env.AI_OFFICE_FUTURE_OVERRIDE, undefined);
assert.equal(process.env.AI_OFFICE_HOOK_ANCESTOR_LOOKUP, 'off');
assert.notEqual(process.env.AI_OFFICE_HOME, ${JSON.stringify(root)});
const config=loadOfficeConfig();assert.equal(config.configured,false);assert.equal(config.mode,'disabled');
writeFileSync(${JSON.stringify(marker)}, 'passed');
`);
  const parentEnvironment = { ...process.env }; delete parentEnvironment.NODE_TEST_CONTEXT;
  await run(process.execPath, [fileURLToPath(new URL('../scripts/run-tests.mjs', import.meta.url)), check], { env: { ...parentEnvironment, AI_OFFICE_CONFIG: config, AI_OFFICE_HOME: root, AI_OFFICE_URL: 'http://127.0.0.1:9876', AI_OFFICE_MODE: 'enabled', AI_OFFICE_WORKSPACE: root, AI_OFFICE_FUTURE_OVERRIDE: 'wrong' } });
  assert.equal(await readFile(marker, 'utf8'), 'passed');
});
